    fun getPositionalBonus(type: PieceType, color: PieceColor, square: Square): Int {
        // In the table above, rank 7 is top of table, rank 0 is bottom
        val tableRow = if (color == PieceColor.WHITE) 7 - square.rank else square.rank
        val tableIndex = tableRow * 8 + square.file

        val table = when (type) {
            PieceType.PAWN -> PAWN_TABLE
            PieceType.KNIGHT -> KNIGHT_TABLE
            PieceType.BISHOP -> BISHOP_TABLE
            PieceType.ROOK -> ROOK_TABLE
            PieceType.QUEEN -> QUEEN_TABLE
            PieceType.KING -> KING_MIDDLEGAME_TABLE
        }
        return table[tableIndex]
    }
